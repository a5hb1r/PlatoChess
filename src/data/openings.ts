export function linesByFamily(family: string): OpeningLine[] {
  return OPENING_LINES.filter((l) => l.family === family);
}

export function openingLineAvailable(
  line: OpeningLine,
  isPro: boolean,
  isMaster: boolean
): boolean {
  if (line.tier === "free") return true;
  if (line.tier === "pro") return isPro || isMaster;
  return isMaster;
}
